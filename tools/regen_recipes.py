def _lua_list(values):
    return '{ ' + ''.join('%d, ' % v for v in values) + '}'


def skill_line(r):
    return ('        { result = %d, count = %d, id = %d, crystal = %d, keyItem = %d, ingredients = %s, '
            'skills = %s,  },' % (r['result'], r['count'], r['id'], r['crystal'], r['keyItem'],
                                  _lua_list(r['ingredients']), _lua_list(r['skills'])))


def write_skill_file(recipes, provenance):
    lists = {c: [] for c in range(1, 9)}
    for r in recipes:
        lists[main_craft(r['skills'])].append(r)
    out = ['---@diagnostic disable', '']
    for p in provenance:
        out.append('-- ' + p)
    if provenance:
        out.append('')
    out.append('local recipesBySkill = {')
    out.append('    [0] = { },')
    for c in range(1, 9):
        out.append('    [%d] = {' % c)
        for r in sorted(lists[c], key=lambda r: r['id']):
            out.append(skill_line(r))
        out.append('    },')
    out.append('}')
    out.append('')
    out.append('return recipesBySkill')
    out.append('')
    return '\n'.join(out), lists


def write_ingredients_file(winners, current_order, current_keys, provenance):
    crystal_order = list(current_order)
    for c in sorted({k[0] for k in winners}):
        if c not in crystal_order:
            crystal_order.append(c)
    by_crystal = collections.defaultdict(list)
    for c in crystal_order:
        seen = set()
        for key in current_keys.get(c, []):
            if (c, key) in winners and key not in seen:
                by_crystal[c].append(key)
                seen.add(key)
        new = [(winners[k]['ID'], k[1]) for k in winners if k[0] == c and k[1] not in seen]
        for _, key in sorted(new):
            by_crystal[c].append(key)
    out = ['---@diagnostic disable', '', '--[[']
    for p in provenance:
        out.append('    ' + p)
    out.append(']]')
    out.append('')
    out.append('local recipeMap = T{ }')
    for c in crystal_order:
        if not by_crystal[c]:
            continue
        out.append('recipeMap[%d] = T{ };' % c)
        for key in by_crystal[c]:
            out.append('recipeMap[%d]["%s"] = T{ };' % (c, key))
    for c in crystal_order:
        for key in by_crystal[c]:
            row = winners[(c, key)]
            out.append('recipeMap[%d]["%s"]["count"] = %d;' % (c, key, row['ResultQty']))
            out.append('recipeMap[%d]["%s"]["itemId"] = %d;' % (c, key, row['Result']))
    out.append('return recipeMap')
    out.append('')
    return '\n'.join(out), by_crystal


