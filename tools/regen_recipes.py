def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--sql', required=True, help='LSB sql/synth_recipes.sql')
    ap.add_argument('--current', help='folder with the current recipesBySkill.lua and recipesByIngredients.lua')
    ap.add_argument('--out', required=True, help='folder to write the new files to')
    ap.add_argument('--commit', default='unknown', help='LSB commit hash, written into the file headers')
    ap.add_argument('--era', choices=sorted(ERA_PRESETS), help='keep only rows whose content_tag is in this preset')
    ap.add_argument('--keep-tags', help='comma list of content_tag values to keep (NULL for untagged)')
    ap.add_argument('--drop-tags', help='comma list of content_tag values to drop (NULL for untagged)')
    ap.add_argument('--include-commented', action='store_true',
                    help='also use rows commented out in the SQL (an LSB server does not load these)')
    ap.add_argument('--levels-from', help='a second synth_recipes.sql to take real craft levels from (see merge_levels)')
    ap.add_argument('--levels-commit', default='unknown', help='commit hash of --levels-from, for the headers')
    ap.add_argument('--levels-label', default='AirSkyBoat sql/synth_recipes.sql',
                    help='what --levels-from is, for the headers')
    ap.add_argument('--fixes', nargs='+', help='JSON files of a server\'s own recipe changes (see load_fixes)')
    ap.add_argument('--eras', choices=sorted(ERA_PRESETS),
                    help='keep every era, and write recipeEras.lua listing the recipes outside this preset')
    ap.add_argument('--desynth-keys', action='store_true',
                    help='also put live desynthesis rows in recipesByIngredients.lua')
    ap.add_argument('--moves', action='store_true',
                    help='also write recipeMoves.lua from --current, which must be HCrafter 1.3.1\'s data '
                         '(see write_moves_file)')
    args = ap.parse_args(argv)
    if args.era and args.eras:
        ap.error('--era drops rows and --eras lists them: use one')
    if args.current and os.path.realpath(args.out) == os.path.realpath(args.current):
        ap.error('--out is the --current folder: write somewhere else, then copy')
    if args.moves and not args.current:
        ap.error('--moves needs --current')
    if args.moves:
        sp = os.path.join(args.current, 'recipesBySkill.lua')
        if not os.path.isfile(sp):
            ap.error('--moves needs recipesBySkill.lua in the --current folder')
        with open(sp, encoding='utf-8') as f:
            made_by_tool = MADE_BY_TOOL.search(f.read(2000)) is not None
        if made_by_tool:
            ap.error('--moves needs HCrafter 1.3.1\'s recipesBySkill.lua in --current, not a table this tool made')
        if not read_skill_file(sp):
            ap.error('--moves needs HCrafter 1.3.1\'s recipesBySkill.lua in --current: %s holds no recipes' % sp)

    def tagset(s):
        return {None if t.strip().upper() == 'NULL' else t.strip() for t in s.split(',') if t.strip()}

    keep = set(ERA_PRESETS[args.era]) if args.era else None
    if args.keep_tags:
        keep = (keep or set()) | tagset(args.keep_tags)
    drop = tagset(args.drop_tags) if args.drop_tags else None

    cols, rows, problems = parse_synth_sql(args.sql)
    if 'content_tag' not in cols and (keep is not None or drop is not None):
        print('warning: this SQL has no content_tag column, so every row counts as untagged', file=sys.stderr)
    kept, skipped = select_rows(rows, args.include_commented, keep, drop)
    recipes = [row_to_recipe(r) for r in kept]
    tag_of = {r['ID']: r.get('content_tag') for r in kept}

    level_stats = None
    if args.levels_from:
        _, other_rows, _ = parse_synth_sql(args.levels_from)
        level_stats = apply_levels_from(recipes, other_rows)

    fix_stats = None
    if args.fixes:
        fixes, remove = load_fixes(args.fixes)
        recipes, fix_stats = apply_fixes(recipes, fixes, remove)

    def tags_text(tags):
        return ', '.join(sorted('NULL' if t is None else t for t in tags))

    filt = 'none'
    if args.era:
        filt = 'era %s (content_tag %s)' % (args.era, tags_text(keep))
    elif keep is not None:
        filt = 'keep content_tag %s' % tags_text(keep)
    if drop is not None:
        filt += '; drop content_tag %s' % tags_text(drop)
    provenance = [
        'Generated by %s from LandSandBoat sql/synth_recipes.sql' % SCRIPT,
        'at commit %s. %s rows only, no desynthesis rows. Era filter: %s.'
        % (args.commit, 'Live and commented-out' if args.include_commented else 'Live', filt),
    ]
    if args.levels_from:
        provenance.append('Craft levels merged from %s at commit %s (see merge_levels in %s).'
                          % (args.levels_label, args.levels_commit, SCRIPT))
    if args.fixes:
        provenance.append('Server changes applied from %s (see apply_fixes in %s).'
                          % (', '.join(os.path.basename(p) for p in args.fixes), SCRIPT))

    os.makedirs(args.out, exist_ok=True)
    skill_text, lists = write_skill_file(recipes, provenance)

    cur_order, cur_keys, cur_values = list(CURRENT_CRYSTAL_ORDER), {}, {}
    cur_skill = None
    if args.current:
        sp = os.path.join(args.current, 'recipesBySkill.lua')
        ip = os.path.join(args.current, 'recipesByIngredients.lua')
        if os.path.exists(sp):
            cur_skill = read_skill_file(sp)
        if os.path.exists(ip):
            cur_order, cur_keys, cur_values = read_ingredients_file(ip)
    winners, collisions = build_ingredient_map_from_recipes(recipes)
    desynth_added = None
    if args.desynth_keys:
        desynth_added = add_desynth_keys(winners, rows, args.include_commented, keep, drop)
    ing_provenance = list(provenance)
    if args.desynth_keys:
        ing_provenance.append('This map also holds the live desynthesis rows (main result and count), so a desynthesis is named by its main result.')
    ing_text, _ = write_ingredients_file(winners, cur_order, cur_keys, ing_provenance)

    with open(os.path.join(args.out, 'recipesBySkill.lua'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(skill_text)
    with open(os.path.join(args.out, 'recipesByIngredients.lua'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(ing_text)
    moves = None
    if args.moves:
        moves_text, moved, changed = write_moves_file(cur_skill, recipes, provenance)
        with open(os.path.join(args.out, 'recipeMoves.lua'), 'w', encoding='utf-8', newline='\n') as f:
            f.write(moves_text)
        moves = (moved, changed)
    later = None
    if args.eras:
        preset = ERA_PRESETS[args.eras]
        later = {r['id'] for r in recipes if tag_of.get(r['id']) not in preset}
        with open(os.path.join(args.out, 'recipeEras.lua'), 'w', encoding='utf-8', newline='\n') as f:
            f.write(write_era_file(later, args.eras, provenance))

    lines = ['source: %s (commit %s)' % (args.sql, args.commit)]
    lines.append('rows in SQL: %d (%d live, %d commented out). Insert-like lines not read: %d'
                 % (len(rows), sum(1 for r in rows if not r['_commented']),
                    sum(1 for r in rows if r['_commented']), len(problems)))
    lines.append('rows used: %d' % len(kept))
    for why, n in sorted(skipped.items()):
        lines.append('  skipped, %s: %d' % (why, n))
    if level_stats is not None:
        lines.append('levels from %s (commit %s):' % (args.levels_from, args.levels_commit))
        for k, v in sorted(level_stats.items()):
            lines.append('  %s: %d' % (k, v))
    if fix_stats is not None:
        lines.append('fixes from %s:' % ', '.join(args.fixes))
        for k, v in sorted(fix_stats.items()):
            lines.append('  %s: %d' % (k, v))
    if later is not None:
        lines.append('recipeEras.lua: %d recipes outside the %s preset' % (len(later), args.eras))
    if moves is not None:
        lines.append('recipeMoves.lua: %d items whose recipe list changed, %d ids that now make another item' % moves)
    if desynth_added is not None:
        lines.append('desynthesis keys added to recipesByIngredients.lua: %d' % desynth_added)
    lines.append('recipesBySkill.lua: %d recipes' % len(recipes))
    for c in range(1, 9):
        lines.append('  craft %d: %d' % (c, len(lists[c])))
    still = sum(1 for r in recipes if PLACEHOLDER in r['skills'])
    lines.append('  recipes that still carry a 255 level: %d' % still)
    lines.append('recipesByIngredients.lua: %d keys, %d keys shared by more than one row (last row wins)'
                 % (len(winners), len(collisions)))
    if cur_skill is not None:
        lines.append('against current recipesBySkill.lua (%d recipes):' % len(cur_skill))
        for k, v in sorted(diff_skill(cur_skill, recipes).items(), key=lambda kv: (kv[0].startswith('  '), kv[0])):
            lines.append('  %s: %d' % (k, v))
        removed, added = line_diff_counts(os.path.join(args.current, 'recipesBySkill.lua'), skill_text)
        lines.append('  text lines only in current: %d, only in proposed: %d' % (removed, added))
    if cur_values:
        lines.append('against current recipesByIngredients.lua (%d keys):' % len(cur_values))
        for k, v in sorted(diff_ingredients(cur_values, winners).items()):
            lines.append('  %s: %d' % (k, v))
        removed, added = line_diff_counts(os.path.join(args.current, 'recipesByIngredients.lua'), ing_text)
        lines.append('  text lines only in current: %d, only in proposed: %d' % (removed, added))
    summary = '\n'.join(lines) + '\n'
    with open(os.path.join(args.out, 'regen_summary.txt'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(summary)
    print(summary, end='')
    return 0


if __name__ == '__main__':
    sys.exit(main())
