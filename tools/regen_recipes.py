SKILL_LINE_RE = re.compile(
    r'^        \{ result = (\d+), count = (\d+), id = (\d+), crystal = (\d+), keyItem = (\d+), '
    r'ingredients = \{ ((?:\d+, )*)\}, skills = \{ ((?:\d+, ){8})\},  \},$')


def _ints(s):
    return [int(x) for x in s.split(',') if x.strip()]


def read_skill_file(path):
    """Recipes from a recipesBySkill.lua, each with its '_list' (craft list index)."""
    out = []
    current = None
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.rstrip('\n')
            m = re.match(r'^    \[(\d+)\] = \{', line)
            if m:
                current = int(m.group(1))
                continue
            m = SKILL_LINE_RE.match(line)
            if m:
                out.append({
                    'result': int(m.group(1)), 'count': int(m.group(2)), 'id': int(m.group(3)),
                    'crystal': int(m.group(4)), 'keyItem': int(m.group(5)),
                    'ingredients': _ints(m.group(6)), 'skills': _ints(m.group(7)), '_list': current,
                })
    return out


ING_KEY_RE = re.compile(r'^recipeMap\[(\d+)\]\["([\d,]+)"\] = T\{ \};$')
ING_VAL_RE = re.compile(r'^recipeMap\[(\d+)\]\["([\d,]+)"\]\["(count|itemId)"\] = (\d+);$')


def read_ingredients_file(path):
    """(crystal order, {crystal: [keys in file order]}, {(crystal, key): {count, itemId}})."""
    order, keys, values = [], collections.OrderedDict(), {}
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.rstrip('\n')
            m = re.match(r'^recipeMap\[(\d+)\] = T\{ \};$', line)
            if m:
                c = int(m.group(1))
                order.append(c)
                keys.setdefault(c, [])
                continue
            m = ING_KEY_RE.match(line)
            if m:
                keys.setdefault(int(m.group(1)), []).append(m.group(2))
                continue
            m = ING_VAL_RE.match(line)
            if m:
                values.setdefault((int(m.group(1)), m.group(2)), {})[m.group(3)] = int(m.group(4))
    return order, keys, values


