def row_to_recipe(row):
    """The fields HCrafter keeps, from one SQL row."""
    return {
        'result': row['Result'],
        'count': row['ResultQty'],
        'id': row['ID'],
        'crystal': row['Crystal'],
        'keyItem': row['KeyItem'],
        'ingredients': sorted(row[c] for c in INGREDIENT_COLUMNS if row[c] != 0),
        'skills': [row[c] for c in CRAFT_COLUMNS],
    }


def main_craft(skills):
    """Highest level, lowest craft id on a tie (synthutils.cpp). None if all 0."""
    craft, level = None, 0
    for i, lv in enumerate(skills, 1):
        if lv > level:
            craft, level = i, lv
    return craft


def ingredient_key(ingredients):
    return ','.join(str(x) for x in sorted(i for i in ingredients if i))


def select_rows(rows, include_commented=False, keep_tags=None, drop_tags=None):
    """Rows that go into the HCrafter tables, plus a Counter of why others did not."""
    kept, skipped = [], collections.Counter()
    for row in rows:
        if row['_commented'] and not include_commented:
            skipped['commented out in the SQL'] += 1
            continue
        if row['Desynth'] != 0:
            skipped['desynthesis row'] += 1
            continue
        tag = row.get('content_tag')
        if keep_tags is not None and tag not in keep_tags:
            skipped['era filter (content_tag %s)' % ('NULL' if tag is None else tag)] += 1
            continue
        if drop_tags is not None and tag in drop_tags:
            skipped['era filter (content_tag %s)' % ('NULL' if tag is None else tag)] += 1
            continue
        if main_craft([row[c] for c in CRAFT_COLUMNS]) is None:
            skipped['no craft level at all'] += 1
            continue
        kept.append(row)
    return kept, skipped


def merge_levels(lsb_skills, other_skills):
    """Craft levels from LSB, with real levels from the other source.

    Per craft, with l the LSB level and a the other source's level:
      - l is the 255 placeholder: use a (even 0) unless a is 255 too
      - l and a are both real levels (1 to 254) and differ: use a
      - otherwise keep l (so LSB decides which crafts take part, and a
        sub-craft LSB added stays)
    """
    out = []
    for l, a in zip(lsb_skills, other_skills):
        if l == PLACEHOLDER:
            out.append(a if a != PLACEHOLDER else l)
        elif 0 < l < PLACEHOLDER and 0 < a < PLACEHOLDER:
            out.append(a)
        else:
            out.append(l)
    return out


def apply_levels_from(recipes, other_rows):
    """Replace levels in recipes (in place) from other_rows. Returns a Counter."""
    by_id = collections.defaultdict(list)
    for r in other_rows:
        if not r['_commented'] and r['Desynth'] == 0:
            by_id[r['ID']].append(r)
    stats = collections.Counter()
    for rec in recipes:
        match = [r for r in by_id.get(rec['id'], []) if r['Result'] == rec['result']]
        if not match:
            stats['no matching live row in the levels source'] += 1
            continue
        merged = merge_levels(rec['skills'], [match[0][c] for c in CRAFT_COLUMNS])
        if main_craft(merged) is None:
            stats['merge left no craft level, kept LSB levels'] += 1
            continue
        if merged != rec['skills']:
            stats['recipes with levels taken from the levels source'] += 1
            stats['levels changed'] += sum(1 for x, y in zip(merged, rec['skills']) if x != y)
            if main_craft(merged) != main_craft(rec['skills']):
                stats['recipes whose main craft changed'] += 1
            rec['skills'] = merged
        else:
            stats['recipes with the same levels in both'] += 1
    return stats


def load_fixes(paths):
    """Merge fix files. Each is a JSON object:

      {"recipes": {"<id>": {"skills": {"<craft 1-8>": level}, "count": n,
                            "crystal": id, "keyItem": id, "ingredients": [ids],
                            "why": "..."}},
       "remove": {"<id>": "why"}}

    Keys other than these are ignored, so a file can carry notes. A later
    file wins over an earlier one for the same field."""
    import json
    recipes, remove = {}, {}
    for path in paths or []:
        with open(path, encoding='utf-8') as f:
            data = json.load(f)
        for rid, change in (data.get('recipes') or {}).items():
            dst = recipes.setdefault(int(rid), {})
            for k, v in change.items():
                if k == 'skills':
                    dst.setdefault('skills', {}).update({int(c): int(lv) for c, lv in v.items()})
                elif k in ('count', 'crystal', 'keyItem'):
                    dst[k] = int(v)
                elif k == 'ingredients':
                    dst[k] = sorted(int(x) for x in v)
        for rid, why in (data.get('remove') or {}).items():
            remove[int(rid)] = why
    return recipes, remove


def apply_fixes(recipes, fixes, remove):
    """Apply fixes (in place) and drop removed recipes. Returns the kept list
    and a Counter. An id that matches no recipe is counted, never guessed."""
    stats = collections.Counter()
    by_id = {r['id']: r for r in recipes}
    for rid, change in sorted(fixes.items()):
        rec = by_id.get(rid)
        if rec is None:
            stats['fix for an id not in the table'] += 1
            continue
        changed = False
        for craft, level in change.get('skills', {}).items():
            if not 1 <= craft <= 8:
                stats['fix with a craft outside 1 to 8'] += 1
                continue
            if rec['skills'][craft - 1] != level:
                rec['skills'][craft - 1] = level
                stats['levels changed by fixes'] += 1
                changed = True
        for k in ('count', 'crystal', 'keyItem', 'ingredients'):
            if k in change and rec[k] != change[k]:
                rec[k] = change[k]
                stats['%s changed by fixes' % k] += 1
                changed = True
        if main_craft(rec['skills']) is None:
            raise SystemExit('fix for recipe %d leaves it with no craft level' % rid)
        stats['recipes changed by fixes' if changed else 'fixes already matching'] += 1
    kept = []
    for rec in recipes:
        if rec['id'] in remove:
            stats['recipes removed by fixes'] += 1
        else:
            kept.append(rec)
    missing = set(remove) - set(by_id)
    if missing:
        stats['removals for an id not in the table'] += len(missing)
    return kept, stats


def build_ingredient_map_from_recipes(recipes):
    """{(crystal, key): {ID, Result, ResultQty}} from the final recipes (fixes
    included), in the order their rows were loaded. LSB's rule: the row
    loaded last wins a shared key."""
    winners, collisions = {}, collections.defaultdict(list)
    for rec in recipes:
        k = (rec['crystal'], ingredient_key(rec['ingredients']))
        if k in winners:
            collisions[k].append(winners[k]['ID'])
        winners[k] = {'ID': rec['id'], 'Result': rec['result'], 'ResultQty': rec['count']}
    return winners, collisions


def add_desynth_keys(winners, rows, include_commented=False, keep_tags=None, drop_tags=None):
    """Adds live desynthesis rows to an ingredient map (in place), in file
    order, the later row winning a shared key, never over a synthesis key.
    Returns how many keys were added."""
    taken = set(winners)
    added = {}
    for row in rows:
        if row['Desynth'] == 0 or (row['_commented'] and not include_commented):
            continue
        tag = row.get('content_tag')
        if (keep_tags is not None and tag not in keep_tags) or (drop_tags is not None and tag in drop_tags):
            continue
        rec = row_to_recipe(row)
        k = (rec['crystal'], ingredient_key(rec['ingredients']))
        if k in taken:
            continue
        added[k] = {'ID': rec['id'], 'Result': rec['result'], 'ResultQty': rec['count']}
    winners.update(added)
    return len(added)


def option_order(recipes):
    """{ result: [ids] } with HCrafter's order: no key item first, then the
    lowest highest level, then the lowest id."""
    by_result = collections.defaultdict(list)
    for r in recipes:
        by_result[r['result']].append(r)
    out = {}
    for result, lst in by_result.items():
        lst.sort(key=lambda r: (r['keyItem'] > 0, max(r['skills']), r['id']))
        out[result] = [r['id'] for r in lst]
    return out


def write_moves_file(current, recipes, provenance):
    """The current table's option order for each item whose list changed in
    any way (a list that only grew is listed too, so an old place past its
    end still means the old last recipe), and the ids that now make another
    item. Returns the text and two counts."""
    old_order, new_order = option_order(current), option_order(recipes)
    moved = {}
    for result, ids in old_order.items():
        if new_order.get(result, []) != ids:
            moved[result] = ids
    new_result = {r['id']: r['result'] for r in recipes}
    changed = {r['id']: r['result'] for r in current
               if r['id'] in new_result and new_result[r['id']] != r['result']}
    out = ['---@diagnostic disable', '']
    for p in provenance:
        out.append('-- ' + p)
    out.append('-- What changed from the previous table, so a recipe named by its place')
    out.append('-- in an item\'s list can still be found.')
    out.append('')
    out.append('return {')
    out.append('    -- the recipes that made an item before, easiest first, for each')
    out.append('    -- item whose list changed')
    out.append('    options = {')
    for result in sorted(moved):
        out.append('        [%d] = %s,' % (result, _lua_list(moved[result])))
    out.append('    },')
    out.append('    -- recipe ids that made another item before: the item they made')
    out.append('    madeBefore = {')
    for rid in sorted(changed):
        out.append('        [%d] = %d,' % (rid, changed[rid]))
    out.append('    },')
    out.append('}')
    out.append('')
    return '\n'.join(out), len(moved), len(changed)


def write_era_file(ids, preset, provenance):
    out = ['---@diagnostic disable', '']
    for p in provenance:
        out.append('-- ' + p)
    out.append('-- The ids of recipes whose content_tag is outside the %s preset, as a set.' % preset)
    out.append('')
    out.append('return {')
    for rid in sorted(ids):
        out.append('    [%d] = true,' % rid)
    out.append('}')
    out.append('')
    return '\n'.join(out)


