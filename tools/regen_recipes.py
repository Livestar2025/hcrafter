def diff_skill(current, proposed):
    cur = {r['id']: r for r in current}
    new = {r['id']: r for r in proposed}
    counts = collections.Counter()
    for rid in cur.keys() | new.keys():
        a, b = cur.get(rid), new.get(rid)
        if a is None:
            counts['recipes added (new id)'] += 1
            continue
        if b is None:
            counts['recipes removed (id gone)'] += 1
            continue
        changed = False
        for field in ('result', 'count', 'crystal', 'keyItem', 'ingredients', 'skills'):
            if a[field] != b[field]:
                counts['  %s changed' % field] += 1
                changed = True
        if a['_list'] != main_craft(b['skills']):
            counts['  moved to another craft list'] += 1
            changed = True
        counts['recipes kept, changed' if changed else 'recipes kept, unchanged'] += 1
    return counts


def diff_ingredients(cur_values, winners):
    counts = collections.Counter()
    new = {k: {'count': r['ResultQty'], 'itemId': r['Result']} for k, r in winners.items()}
    for k in cur_values.keys() | new.keys():
        a, b = cur_values.get(k), new.get(k)
        if a is None:
            counts['keys added'] += 1
        elif b is None:
            counts['keys removed'] += 1
        elif a != b:
            counts['keys with a different itemId or count'] += 1
        else:
            counts['keys unchanged'] += 1
    return counts


def line_diff_counts(old_path, new_text):
    """Lines only in the old file and lines only in the new file (as multisets)."""
    with open(old_path, encoding='utf-8') as f:
        old = collections.Counter(f.read().splitlines())
    new = collections.Counter(new_text.splitlines())
    return sum((old - new).values()), sum((new - old).values())


