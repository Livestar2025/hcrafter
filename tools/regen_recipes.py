def parse_create_table(text, table):
    """Column names, in order, from the CREATE TABLE statement for table."""
    m = re.search(r'CREATE TABLE `%s` \((.*?)\n\)' % re.escape(table), text, re.S)
    if not m:
        raise ValueError('no CREATE TABLE for %s' % table)
    cols = []
    for line in m.group(1).splitlines():
        cm = re.match(r'\s*`(\w+)`\s', line)
        if cm:
            cols.append(cm.group(1))
    return cols


def parse_tuple(s, i):
    """Parse one SQL value tuple starting at s[i] == '('.

    Returns (values, index after the closing paren). Values are int, str or
    None (NULL). Anything else (an @VARIABLE expression, say) comes back as a
    string that starts with '@expr:'.
    """
    if s[i] != '(':
        raise ValueError('expected ( at %d' % i)
    i += 1
    vals = []
    n = len(s)
    while True:
        while i < n and s[i] in ' \t':
            i += 1
        if i >= n:
            raise ValueError('unterminated tuple')
        ch = s[i]
        if ch == "'":
            i += 1
            buf = []
            while True:
                if i >= n:
                    raise ValueError('unterminated string')
                c = s[i]
                if c == '\\' and i + 1 < n:
                    nxt = s[i + 1]
                    buf.append({'n': '\n', 't': '\t', 'r': '\r', '0': '\0'}.get(nxt, nxt))
                    i += 2
                    continue
                if c == "'":
                    if i + 1 < n and s[i + 1] == "'":
                        buf.append("'")
                        i += 2
                        continue
                    i += 1
                    break
                buf.append(c)
                i += 1
            vals.append(''.join(buf))
        elif s.startswith('NULL', i):
            vals.append(None)
            i += 4
        else:
            j = i
            depth = 0
            while j < n and not (depth == 0 and s[j] in ',)'):
                if s[j] == '(':
                    depth += 1
                elif s[j] == ')':
                    depth -= 1
                j += 1
            raw = s[i:j].strip()
            vals.append(int(raw) if re.fullmatch(r'-?\d+', raw) else '@expr:' + raw)
            i = j
        while i < n and s[i] in ' \t':
            i += 1
        if i >= n:
            raise ValueError('unterminated tuple')
        if s[i] == ',':
            i += 1
            continue
        if s[i] == ')':
            return vals, i + 1
        raise ValueError('unexpected %r at %d' % (s[i], i))


def parse_synth_sql(path):
    """All synth_recipes rows in file order.

    Returns (columns, rows, problems). Each row is a dict keyed by column name
    plus '_line' (1-based line number), '_commented' (True for a
    "-- INSERT INTO ..." line) and '_note' (a trailing "-- ..." comment).
    Insert-like lines that do not parse into the right number of integer
    columns (the template line, rows with more than 8 materials) go to
    problems as (line number, reason, text).
    """
    with open(path, encoding='utf-8') as f:
        text = f.read()
    cols = parse_create_table(text, 'synth_recipes')
    int_cols = [c for c in cols if c not in ('ResultName', 'content_tag')]
    rows, problems = [], []
    for lineno, line in enumerate(text.splitlines(), 1):
        m = INSERT_RE.match(line)
        if not m or m.group('table') != 'synth_recipes':
            continue
        rest = m.group('rest')
        try:
            vals, end = parse_tuple(rest, 0)
        except ValueError as e:
            problems.append((lineno, 'parse error: %s' % e, line))
            continue
        tail = rest[end:].strip()
        if tail.startswith(','):
            problems.append((lineno, 'multi-row insert not supported', line))
            continue
        note = ''
        if tail.startswith(';'):
            tail = tail[1:].strip()
        if tail.startswith('--'):
            note = tail[2:].strip()
        if len(vals) != len(cols):
            problems.append((lineno, 'expected %d values, found %d' % (len(cols), len(vals)), line))
            continue
        row = dict(zip(cols, vals))
        if any(not isinstance(row[c], int) for c in int_cols):
            problems.append((lineno, 'non-integer value in an integer column', line))
            continue
        row.setdefault('content_tag', None)
        row['_line'] = lineno
        row['_commented'] = bool(m.group('comment'))
        row['_note'] = note
        rows.append(row)
    return cols, rows, problems


