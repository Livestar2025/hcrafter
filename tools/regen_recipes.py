#!/usr/bin/env python3
"""Regenerate HCrafter's two recipe data files from LandSandBoat's SQL.

Reads sql/synth_recipes.sql from a LandSandBoat (LSB) checkout and writes
recipesBySkill.lua and recipesByIngredients.lua in the Lua format and table
shapes HCrafter loads (the files the xitools craft tool shipped). It
refuses an --out folder that is the --current one, so it never writes over
what it reads.

What it does:
  - reads the CREATE TABLE statement and maps columns by name, so a change in
    column order upstream cannot shift values
  - keeps live rows only. A row commented out in the SQL ("-- INSERT INTO")
    is not loaded by an LSB server, so it is skipped (--include-commented
    keeps them, which is what xitools did and is how the 255 levels got in)
  - skips desynthesis rows (Desynth is not 0)
  - keeps LSB's recipe ids, which are the ids the Resource Planner saves
  - puts each recipe in the list of its main craft: the highest level, the
    lowest craft id on a tie (the rule in LSB's synthutils.cpp). xitools
    dropped every recipe with a tie, this keeps them
  - orders each craft list by recipe id, as the current file does
  - in recipesByIngredients.lua, keeps the current file's key order where a
    key survives and appends new keys after it, so a diff stays readable
  - when two kept rows share a crystal and materials, uses the row an LSB
    server ends up with: LoadSynthRecipes() assigns into a map by that key,
    so the row loaded last wins (the later row in the file)
  - optional era filter on LSB's content_tag column (--era, --keep-tags,
    --drop-tags)
  - optional --levels-from: take craft levels from a second synth_recipes.sql
    (for example AirSkyBoat's) where both files have a real level. See
    merge_levels() for the exact rule
  - optional --fixes (one or more JSON files): a server's own changes, by
    recipe id: craft levels, yield, crystal, key item or materials, and
    recipes the server removed. Both files and the summary reflect them.
    See apply_fixes() for the format
  - optional --eras: also write recipeEras.lua, the ids of the recipes whose
    content_tag is outside an era preset, so an addon can hide them behind a
    setting instead of dropping them
  - optional --desynth-keys: also put LSB's live desynthesis rows in
    recipesByIngredients.lua, so a desynthesis in progress is named by its
    main result. A synthesis keeps any key both share
  - optional --moves (needs --current): also write recipeMoves.lua, the
    current table's order of the recipes for each item whose list changed,
    and the recipe ids that now make another item, so settings that named a
    recipe by its place in a list can be carried over. HCrafter's
    recipeMoves.lua is built with --current set to HCrafter 1.3.1's data,
    the table those settings come from. Built against a newer table it would
    break that migration, so leave --moves off and keep the file when you
    rebuild the others

Usage:
  python3 -I regen_recipes.py --sql LSB/sql/synth_recipes.sql --current HCRAFTER/data \\
      --out proposed [--commit HASH] [--era toau | --eras toau] \\
      [--levels-from ASB/sql/synth_recipes.sql --levels-commit HASH] \\
      [--fixes FIXES.json ...] [--desynth-keys] [--moves]

A summary of what changed against --current is printed and written to
<out>/regen_summary.txt.
"""

import argparse
import collections
import os
import re
import sys

CRAFT_COLUMNS = ['Wood', 'Smith', 'Gold', 'Cloth', 'Leather', 'Bone', 'Alchemy', 'Cook']
INGREDIENT_COLUMNS = ['Ingredient%d' % i for i in range(1, 9)]
# crystal section order of the current recipesByIngredients.lua (the order
# the xitools dump came out in). other crystals, if any, go after these.
CURRENT_CRYSTAL_ORDER = [4097, 4099, 4101, 4096, 4098, 4100, 4102, 4103]
PLACEHOLDER = 255
# this script's own name, for the file headers
SCRIPT = os.path.basename(__file__)
# the first header line of a file this tool wrote, whatever the tool's file
# is called
MADE_BY_TOOL = re.compile(r'Generated by \S+ from LandSandBoat sql/synth_recipes\.sql')

# content_tag presets for --era. NULL (no tag) is kept by every preset.
# HorizonXI is a 75-cap era server whose newest expansion is Treasures of
# Aht Urhgan (ToAU).
ERA_PRESETS = {
    'toau': {None, 'ROTZ', 'COP', 'TOAU'},
    'cop': {None, 'ROTZ', 'COP'},
    'rotz': {None, 'ROTZ'},
}

INSERT_RE = re.compile(r'^(?P<comment>--\s*)?INSERT INTO `(?P<table>\w+)` VALUES\s*(?P<rest>\(.*)$')


